const { _electron: electron } = require('playwright-core');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const assert = require('node:assert/strict');
(async () => {
  const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'conductor-preview-ui-'));
  const executablePath = process.argv[2] || require('electron');
  let app;
  try {
    const env = { ...process.env, APPDATA: temp, LOCALAPPDATA: path.join(temp, 'local') }; delete env.ELECTRON_RUN_AS_NODE;
    app = await electron.launch({ executablePath, timeout: 30000, args: process.argv[2] ? [] : ['.'], cwd: path.resolve(__dirname, '..'), env });
    const page = await app.firstWindow();
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    await page.waitForSelector('#codex-settings-dialog[open]');
    await page.fill('#codex-base-url', 'https://example.com/v1');
    await page.fill('#codex-model', 'test-model');
    await page.fill('#codex-api-key', 'fake-ui-key');
    await page.selectOption('#codex-effort', 'high');
    await page.click('#codex-save');
    await page.waitForFunction(() => !document.querySelector('#codex-settings-dialog').open);
    assert.equal(await page.inputValue('#codex-api-key'), '');
    const snapshot = await page.evaluate(() => window.codexdesk.readCodexSettings());
    assert.equal(snapshot.value.model, 'test-model'); assert.equal(snapshot.value.hasApiKey, true);
    assert.ok(!JSON.stringify(snapshot).includes('fake-ui-key'));
    await page.click('#manage-codex-profiles');
    await page.click('#codex-profile-new');
    await page.fill('#codex-profile-name', 'B 服务商');
    await page.fill('#codex-base-url', 'https://b.example.com/v1');
    await page.fill('#codex-model', 'model-b');
    await page.fill('#codex-api-key', 'fake-b-key');
    await page.selectOption('#codex-effort', 'medium');
    await page.click('#codex-save');
    await page.waitForFunction(() => !document.querySelector('#codex-settings-dialog').open);
    const profiles = await page.evaluate(() => window.codexdesk.listCodexProfiles());
    assert.equal(profiles.value.profiles.length, 2);
    const b = profiles.value.profiles.find(item => item.name === 'B 服务商');
    assert.ok(b.hasApiKey); assert.ok(!JSON.stringify(profiles).includes('fake-b-key'));
    await page.click('#btn-sidebar-new-conv');
    await page.click('#create-conversation-confirm');
    await page.waitForFunction(() => !document.querySelector('#conversation-codex-profile').disabled);
    const current = await page.evaluate(() => window.codexdesk.getSnapshot());
    assert.ok(current.activeConversationId);
    if (process.argv[2]) assert.equal(current.settings.defaultWorkdir, path.join(path.dirname(path.resolve(process.argv[2])), 'workspace'));
    page.once('dialog', dialog => dialog.accept());
    await page.selectOption('#conversation-codex-profile', b.id);
    await page.waitForFunction(() => document.querySelector('#codex-profile-status').textContent.includes('已切换'));
    const selected = await page.evaluate(id => window.codexdesk.listCodexProfiles(id), current.activeConversationId);
    assert.equal(selected.value.selectedId, b.id);
    await page.click('#manage-codex-profiles');
    await page.waitForFunction(() => document.querySelector('#codex-profile-name').value === 'B 服务商');
    assert.equal(await page.inputValue('#codex-api-key'), '');
    await page.fill('#codex-api-key', 'replacement-b-key');
    await page.click('#codex-save');
    await page.waitForFunction(() => !document.querySelector('#codex-settings-dialog').open);
    assert.equal(JSON.parse(fs.readFileSync(path.join(temp, 'ConductorInstalled/profiles', b.id, 'auth.json'))).OPENAI_API_KEY, 'replacement-b-key');
    await page.screenshot({ path: path.resolve(__dirname, '../../dist/windows/settings-smoke.png') });
    const userData = await app.evaluate(({ app }) => app.getPath('userData'));
    assert.equal(userData, path.join(temp, 'ConductorInstalled'));
    assert.deepEqual(errors, []);
    await app.close(); app = null;
    app = await electron.launch({ executablePath, timeout: 30000, args: process.argv[2] ? [] : ['.'], cwd: path.resolve(__dirname, '..'), env });
    const page2 = await app.firstWindow(); await page2.waitForSelector('#btn-quick-settings');
    const state = await page2.evaluate(() => window.codexdesk.readCodexSettings());
    assert.equal(state.value.effort, 'high'); assert.equal(state.value.hasApiKey, true);
    const persisted = await page2.evaluate(id => window.codexdesk.listCodexProfiles(id), current.activeConversationId);
    assert.equal(persisted.value.selectedId, b.id);
    assert.equal(persisted.value.profiles.length, 2);
    console.log('PASS: first-run setup, save, secret redaction, isolated userData, restart persistence, renderer errors.');
  } finally {
    if (app) await app.close();
    assert.ok(temp.startsWith(path.join(os.tmpdir(), 'conductor-preview-ui-')));
    fs.rmSync(temp, { recursive: true, force: true, maxRetries: 10, retryDelay: 200 });
  }
})().catch(error => { console.error(error); process.exitCode = 1; });
